function splitScene(value) {
  const [name, ...rest] = String(value || "").split("：");
  return { name: name.trim(), prompt: rest.join("：").trim() };
}

const PURPOSE_SCENE_LIBRARY = Object.freeze(Object.fromEntries(CATEGORY_ORDER.map((categoryId) => {
  const meta = CATEGORY_META[categoryId];
  const scenes = RAW_SCENES[categoryId].map((value, index) => {
    const scene = splitScene(value);
    return Object.freeze({
      id: `${categoryId}-${String(index + 1).padStart(2, "0")}`,
      index: index + 1,
      name: scene.name,
      prompt: scene.prompt
    });
  });
  return [categoryId, Object.freeze({ id: categoryId, ...meta, scenes: Object.freeze(scenes) })];
})));

function creativeSceneCategories(options = {}) {
  const includeScenes = options.includeScenes === true;
  return CATEGORY_ORDER.map((categoryId) => {
    const category = PURPOSE_SCENE_LIBRARY[categoryId];
    return {
      id: category.id,
      label: category.label,
      description: category.description,
      sceneCount: category.scenes.length,
      ...(includeScenes ? { scenes: category.scenes.map((scene) => ({ ...scene })) } : {})
    };
  });
}

function getCreativeSceneCategory(categoryId) {
  return PURPOSE_SCENE_LIBRARY[String(categoryId || "").trim()] || null;
}

function stableHash(value) {
  let hash = 2166136261;
  for (const char of String(value || "")) {
    hash ^= char.codePointAt(0);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

function selectCreativeScenePresets(categoryId, count, seed = "") {
  const category = getCreativeSceneCategory(categoryId);
  if (!category) return [];
  const total = category.scenes.length;
  const wanted = Math.max(1, Math.min(total, Math.trunc(Number(count) || 1)));
  const hash = stableHash(`${categoryId}:${seed}`);
  const strides = [7, 9, 11, 13, 17, 19];
  const start = hash % total;
  const stride = strides[Math.floor(hash / total) % strides.length];
  return Array.from({ length: wanted }, (_, index) => ({ ...category.scenes[(start + index * stride) % total] }));
}

